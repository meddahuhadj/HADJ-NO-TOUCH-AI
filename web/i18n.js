  const DICTS = { fr: FR, ar: AR };
  const protectedEls = new WeakSet(); // already-translated containers (skip their leaves)
  const $$ = (s, c) => Array.prototype.slice.call((c || document).querySelectorAll(s));

  let current = localStorage.getItem(STORE_KEY) || "en";
  if (LANGUAGES.indexOf(current) < 0) current = "en";

  const normalize = (s) => (s || "").replace(/\s+/g, " ").trim();

  const t = (key) => {
    const lang = current;
    if (lang === "en") return key;
    const dict = DICTS[lang];
    if (!dict) return key;
    const v = dict[key];
    return typeof v === "string" ? v : key;
  };

  const setLang = (code, opts) => {
    if (LANGUAGES.indexOf(code) < 0) code = "en";
    if (code === current && !(opts && opts.force)) return current;
    current = code;
    try { localStorage.setItem(STORE_KEY, code); } catch (_) { /* private mode */ }
    apply();
    // notify anything that rebuilds DOM with dynamic strings
    (subs.slice()).forEach((fn) => { try { fn(code); } catch (_) { /* noop */ } });
    return code;
  };

  const getLang = () => current;

  /* translate [data-i18n] and [data-i18n-attrs] elements, then leaf nodes */
  const apply = () => {
    document.documentElement.setAttribute("lang", current);
    document.documentElement.setAttribute("dir", current === "ar" ? "rtl" : "ltr");

    const title = document.querySelector("title");
    if (title) title.textContent = t(title.textContent);

    const protectedCheck = (el, upTo) => {
      for (let p = el; p && p !== upTo; p = p.parentElement) {
        if (protectedEls.has(p)) return true;
      }
      return false;
    };

    $$("[data-i18n]").forEach((el) => {
      const v = t(el.getAttribute("data-i18n"));
      if (v !== el.getAttribute("data-i18n")) el.innerHTML = v;
      protectedEls.add(el);
    });

    $$("[data-i18n-attrs]").forEach((el) => {
      const list = (el.getAttribute("data-i18n-attrs") || "")
        .split(/[|,]/).map((s) => s.trim()).filter(Boolean);
      list.forEach((attr) => {
        const cur = el.getAttribute(attr);
        if (cur) el.setAttribute(attr, t(cur));
      });
      protectedEls.add(el);
    });

    // structured elements (they have nested tags): match by full innerHTML,
    // falling back to the markup-stripped textContent.
    $$("h1, h2, h3, h4, p, li, summary, figcaption, legend, strong, .vcol, .voice-callout")
      .forEach((el) => {
        if (!el.children.length || el.children.length === 0) return;
        if (protectedCheck(el, document.body)) return;
        const inner = normalize(el.innerHTML);
        const text = normalize(el.textContent);
        const v = (current === "en") ? inner : (DICTS[current][inner] || DICTS[current][text]);
        if (v && v !== inner && v !== text) {
          el.innerHTML = v;
          protectedEls.add(el);
        }
      });

    // leaf text nodes
    const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
    const nodes = [];
    while (walker.nextNode()) nodes.push(walker.currentNode);
    nodes.forEach((node) => {
      const parent = node.parentElement;
      if (!parent) return;
      if (protectedCheck(parent, document.body)) return;
      const text = normalize(node.nodeValue);
      if (!text) return;
      const val = t(text);
      if (val !== text) node.nodeValue = val;
    });
  };

  const subs = [];
  const onChange = (fn) => { subs.push(fn); };

  window.HADJ_I18N = { t, setLang, getLang, onChange, apply };

  /* expose helpers used by app.js */
  window.__t = t;
  window.__tf = (tpl, ctx) => t(String(tpl)).replace(/\{(\w+)\}/g, (m, k) => (k in ctx ? ctx[k] : m));

  /* deferred: run after DOM ready */
  document.addEventListener("DOMContentLoaded", () => {
    const sel = document.getElementById("lang-select");
    if (sel) {
      sel.value = current;
      sel.addEventListener("change", () => setLang(sel.value, { force: true }));
    }
    if (current !== "en") apply();
  });
