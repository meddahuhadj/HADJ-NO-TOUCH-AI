def lerp_pose(a: Pose, b: Pose, f: float) -> Pose:
    f = max(0.0, min(1.0, f))
    return [(ax + (bx - ax) * f, ay + (by - ay) * f) for (ax, ay), (bx, by) in zip(a, b)]
